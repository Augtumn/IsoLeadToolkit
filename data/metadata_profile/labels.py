#: 兜底链的最后一环：连英文标签都缺失时用 OID 顶上，保证 ``label_for()`` 永不返回空串。
_FALLBACK_UNKNOWN = "未命名字段"


def label_for(spec: FieldSpec) -> str:
    """取字段的中文标签，逐级回退且保证非空。

    回退顺序：``spec.oid`` → ``EN_LABELS_ZH[spec.label_en]`` → ``spec.label_en`` →
    ``spec.oid`` → ``"未命名字段"``。后面两级只在档案升版、OID 与英文标签都缺失时才触发，
    目的是让表头永不出现空串。

    Args:
        spec: 档案字段定义。

    Returns:
        中文标签；无法翻译时回退到英文标签，再回退到 OID，最终保证非空字符串。
    """
    by_oid = FIELD_LABELS_ZH.get(spec.oid)
    if by_oid:
        return by_oid
    label_en = (spec.label_en or "").strip()
    by_en = EN_LABELS_ZH.get(label_en)
    if by_en:
        return by_en
    if label_en:
        return label_en
    return spec.oid.strip() or _FALLBACK_UNKNOWN


