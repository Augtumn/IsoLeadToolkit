"""由注册表生成 TerraLID 铅同位素数据录入工作簿（Excel 模板）。

`reference/metadata` 是 TerraLID Metadata Profile（英文字段定义）；考古/冶金用户用 Excel
录数据，Python 负责校验与推导。本脚本把 `Profile` 注册表渲染成一张多工作表工作簿：
表名、列序、列宽与数值格式一律取自 `layout.build_layout()`（唯一真源），本模块负责**录入表**
的写入——双层表头、单元格批注、受控词表下拉、必填条件格式——以及命令行入口。

分工与边界：

- `scripts/entry_workbook_info.py` 负责 README / 0_SCHEMA / 0_VOCAB / 99_CHECK 四张信息表
  （只读它的常量与写入函数，方向单向往外）。
- `data/metadata_profile/io_xlsx.py` 负责**读已填工作簿**与回写校验结果，本脚本只做**生成模板**；
  两者共用 `io_xlsx` 的表头约定（`FIRST_DATA_ROW` / `CHECK_HEADERS`），避免两侧漂移。
- 公开 API 只依赖传入的 `Profile`：不做文件系统搜索、不解析 markdown、不导入 PyQt5；只有
  `main()` 才调 `profile.load_profile()`，因此测试可用 `spec.py` 手工构造的注册表独立验证。

命令行::

    python scripts/build_entry_workbook.py [--output PATH] [--profile-root PATH]
                                           [--emit-json PATH] [--force]

目标已存在时默认拒绝覆盖（用户的工作簿可能已填数据），确认后加 ``--force``。
"""
