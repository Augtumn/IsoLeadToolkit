def _range_ref(worksheet: Worksheet, first_row: int, last_row: int, column: int) -> str:
    """单元格区域的绝对引用（含工作表名，供命名区域使用）。"""
    letter = get_column_letter(column)
    coordinates = f"{letter}{first_row}:{letter}{max(last_row, first_row)}"
    return f"{quote_sheetname(worksheet.title)}!{absolute_coordinate(coordinates)}"


def _write_simple_header(
    worksheet: Worksheet, headers: Sequence[str], widths: Sequence[int]
) -> None:
    """写单层表头（加粗 + 浅灰底）并设置列宽。"""
    for index, header in enumerate(headers, start=1):
        cell = worksheet.cell(row=1, column=index, value=header)
        cell.font = HEADER_FONT
        cell.fill = HEADER_FILL
    for index, width in enumerate(widths, start=1):
        worksheet.column_dimensions[get_column_letter(index)].width = width


def write_schema_sheet(worksheet: Worksheet, rows: Sequence[Sequence[object]]) -> None:
    """写 `0_SCHEMA`：字段定义总表（冻结首行 + 自动筛选）。"""
    _write_simple_header(worksheet, SCHEMA_HEADERS, SCHEMA_WIDTHS)
    for row_index, row in enumerate(rows, start=2):
        for column_index, value in enumerate(row, start=1):
            worksheet.cell(row=row_index, column=column_index, value=value)
    worksheet.freeze_panes = "A2"
    last = get_column_letter(len(SCHEMA_HEADERS))
    worksheet.auto_filter.ref = f"A1:{last}{max(1, len(rows) + 1)}"


def write_check_sheet(worksheet: Worksheet) -> None:
    """写 `99_CHECK` 表头（列与顺序取自 `io_xlsx`，与导入器共用一份约定）。"""
    _write_simple_header(worksheet, CHECK_HEADERS, CHECK_WIDTHS)
    worksheet.freeze_panes = f"A{CHECK_FIRST_DATA_ROW}"


def _block_hosts(table: TableSpec) -> dict[Block, list[str]]:
    """模块内每个可复用块 → 去重后的宿主字段 OID（保持出现顺序）。"""
    hosts: dict[Block, list[str]] = {}
    for spec in table.fields:
        if spec.block is None or not spec.block_owner:
            continue
        bucket = hosts.setdefault(spec.block, [])
        if spec.block_owner not in bucket:
            bucket.append(spec.block_owner)
    for block in dict.fromkeys(table.inlined_blocks):
        declared = table.inlined_blocks.count(block)
        found = hosts.get(block, [])
        if len(found) < declared:
            logger.warning(
                "模块 %s 内联 %s 共 %d 次，但只解析出 %d 个宿主（%s）：0_SCHEMA 可能少行",
                table.key.value,
                block.value,
                declared,
                len(found),
                found,
            )
    return hosts


def _block_fields(table: TableSpec, block: Block) -> list[FieldSpec]:
    """模块内某可复用块的字段（按 OID 去重，文档顺序）。"""
    collected: dict[str, FieldSpec] = {}
    for spec in table.fields:
        if spec.block is block and spec.oid not in collected:
            collected[spec.oid] = spec
    return sorted(collected.values(), key=lambda spec: (spec.depth, spec.order))


def _schema_row(spec: FieldSpec, host: str) -> list[object]:
    """一个字段在 ``0_SCHEMA`` 里的行内容（列序同 `SCHEMA_HEADERS`）。"""
    return [
        spec.oid,
        spec.key,
        spec.label_zh or spec.label_en,
        spec.label_en,
        f"{spec.table.value} @ {host}" if host else spec.table.value,
        spec.obligation.value,
        spec.occurrence.value,
        ", ".join(provider.value for provider in spec.provided_by),
        spec.value_kind.value,
        spec.vocab_id or "",
        spec.definition,
        spec.allowed,
        spec.example,
        spec.source_doc,
        spec.source_line,
    ]


def schema_rows(profile: Profile) -> list[list[object]]:
    """``0_SCHEMA`` 的数据行（不含表头）。

    口径 = ``sum(len(table.fields) for table in profile.tables)``：模块自有字段一行，内联块
    字段**按宿主各一行**，因此同一个 B6.1 会在 ``analyses`` 里因 A9.3 / A14 两个宿主出现两次
    （`TableSpec.fields` 本就按内联副本逐条记录，故两者数量相等）。表头里没有单独的"宿主"列
    （列序是固定契约），宿主并入"所属模块"列，形如 ``analyses @ A9.3``。

    Args:
        profile: 注册表。

    Returns:
        行列表；列序与 :data:`SCHEMA_HEADERS` 一致。
    """
    rows: list[list[object]] = []
    for table in profile.tables:
        seen_own: set[str] = set()
        for spec in table.fields:
            if spec.block is not None or spec.oid in seen_own:
                continue
            seen_own.add(spec.oid)
            rows.append(_schema_row(spec, ""))
        for block, hosts in _block_hosts(table).items():
            for host in hosts:
                for spec in _block_fields(table, block):
                    rows.append(_schema_row(spec, host))
    return rows


