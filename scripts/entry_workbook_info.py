def group_condition_oid(column: ColumnSpec) -> str | None:
    """该列**最近的**可选分组祖先 OID；没有则 ``None``（真·无条件必填）。

    单一真源：直接用 `ColumnSpec.optional_ancestors`（自近及远、由 `layout.py` 判定），
    不再自行按 ``occurrence`` 重算 —— 否则校验侧与红底条件各算一份，档案调整
    ``occurrence`` 时会悄悄漂移。取最近而非最外层：``SI5.1.1`` 的条件来自 ``SI5.1``
    （其列只有 ``SI5.1.1``/``SI5.1.2``），用 ``SI5`` 会把"填了四至范围"误判成"点位组已启用"。

    跳过可复用块的**块根**（``B1``…``B6``）：块表的一行本身就是"用了这一组"的声明
    （由 ``owner_sheet`` / ``owner_id`` 定位），块根不该成为"组已启用"的条件 —— 否则
    ``B6.1`` 的因子会变成 ``COUNTA(B6.1..B6.7)>0`` 的自我指涉，空的比值行永远不标红。
    块内部的嵌套可选组（如 ``B1.4`` 人员 PID）仍照常作为因子。
    """
    block_oids = {column.block.value} if column.block is not None else set()
    return next(
        (ancestor for ancestor in column.optional_ancestors if ancestor not in block_oids),
        None,
    )


def unconditional_required_oids(sheet: SheetSpec) -> list[str]:
    """必填且**不受可选分组限制**的列 OID（含必填容器内的字段，如 ``A6.1``）。"""
    return [
        column.oid
        for column in sheet.columns
        if column.is_required_from_provider and group_condition_oid(column) is None
    ]


def plain_required_oids(sheet: SheetSpec) -> list[str]:
    """必填且不属于**任何**非列祖先的列 OID（连必填容器也没有，如 ``SI1``）。"""
    column_oids = {column.oid for column in sheet.columns}
    return [
        column.oid
        for column in sheet.columns
        if column.is_required_from_provider
        and not [a for a in column.ancestors if a not in column_oids]
    ]


def chain_entity_sheets(layout: WorkbookLayout) -> list[SheetSpec]:
    """Site → Assemblage → Object → Sample → Analysis 链上的实体表（按层级顺序）。"""
    sheets: list[SheetSpec] = []
    key: TableKey | None = TableKey.ANALYSIS
    while key is not None:
        sheet = layout.sheet_for_table(key)
        if sheet is not None:
            sheets.append(sheet)
        key = key.parent
    return list(reversed(sheets))


def write_vocab_sheet(
    workbook: Workbook,
    worksheet: Worksheet,
    vocab: Mapping[str, list[str]],
    names: Mapping[str, str],
    owner_options: Sequence[str],
) -> None:
    """写 `0_VOCAB`：每张词表一列 + 两列系统清单，并建立命名区域。"""
    labels = _vocab_display_names()
    columns: list[tuple[str, list[str], str]] = [
        (f"{vocab_id} {labels.get(vocab_id, '')}".strip(), list(items), names[vocab_id])
        for vocab_id, items in vocab.items()
    ]
    columns.append(
        (
            f"{ValueKind.RATIO_NAME.value} 铅同位素比值（系统清单）",
            list(LIA_RATIO_NAMES),
            RATIO_NAME_LIST_NAME,
        )
    )
    columns.append(
        (f"{OWNER_SHEET_COLUMN} 所属表（系统清单）", list(owner_options), OWNER_SHEET_LIST_NAME)
    )

    for index, (header, items, defined_name) in enumerate(columns, start=1):
        cell = worksheet.cell(row=1, column=index, value=header)
        cell.font = HEADER_FONT
        cell.fill = HEADER_FILL
        for offset, item in enumerate(items):
            worksheet.cell(row=VOCAB_FIRST_DATA_ROW + offset, column=index, value=item)
        workbook.defined_names.add(
            DefinedName(
                defined_name,
                attr_text=_range_ref(
                    worksheet,
                    VOCAB_FIRST_DATA_ROW,
                    VOCAB_FIRST_DATA_ROW + len(items) - 1,
                    index,
                ),
            )
        )
        longest = max((len(str(item)) for item in items), default=8)
        worksheet.column_dimensions[get_column_letter(index)].width = min(
            40, max(18, longest + 2)
        )
    worksheet.freeze_panes = f"A{VOCAB_FIRST_DATA_ROW}"


def _vocab_display_names() -> dict[str, str]:
    """词表 id → 中文名（`vocab.py` 提供时使用，缺省只有 id）。"""
    try:
        from data.metadata_profile import vocab as module
    except ImportError as err:
        logger.warning("受控词表模块不可用，0_VOCAB 表头只写词表 id: %s", err)
        return {}
    raw = getattr(module, "VOCABULARIES", None)
    if not isinstance(raw, Mapping):
        return {}
    names: dict[str, str] = {}
    for vocab_id, value in raw.items():
        label = getattr(value, "label_zh", None)
        if isinstance(value, Mapping):
            label = value.get("label_zh", label)
        if label:
            names[str(vocab_id)] = str(label)
    return names


def _format_column_list(sheet: SheetSpec, oids: Sequence[str]) -> str:
    """``OID（中文标签）`` 列表；标签缺失时只写 OID。"""
    parts: list[str] = []
    for oid in oids:
        column = sheet.column(oid)
        label = (column.label_zh or column.label_en) if column is not None else ""
        parts.append(f"{oid}（{label}）" if label else oid)
    return "、".join(parts)


